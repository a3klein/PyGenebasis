GENE_SEARCH_N_TYPES   = 5   # number of cell types in gene_search_adata
GENE_SEARCH_N_MARKERS = 5   # marker genes per type (25 informative out of 200)


@pytest.fixture(scope="session")
def gene_search_adata() -> ad.AnnData:
    """Synthetic AnnData designed to stress-test gene_search and retain_informative_genes.

    Design goals (addressing limitations of small_adata):
    - 5 cell types instead of 3 — more complex class structure
    - Only 25 informative genes (5 per type, interleaved: type t → genes t, t+5, ...,
      t+20), out of 200 total — most genes are pure noise
    - High SNR: in-class expression Poisson(λ=20→12), background Poisson(λ=0.1) —
      a ~100× contrast makes the informative set unmistakable for HVG selection
    - Decreasing marker strength (20→12) gives a clear preference ordering within
      each type so that gene_search has a steep score landscape for the first ~5
      selections per type, then drops off sharply into noise

    The 25 informative gene indices are 0..24 (interleaved by cell type).
    Genes 25..199 are pure Poisson(0.1) noise.
    """
    rng = np.random.default_rng(7)
    n_types = GENE_SEARCH_N_TYPES
    n_markers = GENE_SEARCH_N_MARKERS
    n_cells_per_type = 50
    n_genes = 200

    cell_types = [f"Type{chr(65+t)}" for t in range(n_types)]  # TypeA .. TypeE
    labels = np.repeat(cell_types, n_cells_per_type)
    n_cells = n_cells_per_type * n_types

    # Background: very low expression so noise genes are easy to distinguish
    counts = rng.poisson(lam=0.1, size=(n_cells, n_genes)).astype(np.float32)

    # Interleaved markers: type t gets genes t, t+n_types, t+2*n_types, ...
    # Decreasing lambdas give a clear greedy preference ordering.
    lams = np.linspace(20.0, 12.0, n_markers)
    for t, ct in enumerate(cell_types):
        marker_cols = list(range(t, t + n_markers * n_types, n_types))
        cell_rows = np.where(labels == ct)[0]
        for j, col in enumerate(marker_cols):
            counts[np.ix_(cell_rows, [col])] = (
                rng.poisson(lam=lams[j], size=(n_cells_per_type, 1)).astype(np.float32)
            )

    counts = np.log1p(counts)

    obs = pd.DataFrame(
        {
            "celltype": labels,
            "batch": rng.choice(["batch1", "batch2"], size=n_cells),
        },
        index=[f"cell_{i}" for i in range(n_cells)],
    )
    var = pd.DataFrame(index=[f"gene_{i}" for i in range(n_genes)])
    return ad.AnnData(X=scipy.sparse.csr_matrix(counts), obs=obs, var=var)


