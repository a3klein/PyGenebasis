def _load_adata(dataset_dir: Path) -> ad.AnnData:
    """Load a reference dataset as AnnData from MTX + CSV files."""
    if not dataset_dir.exists():
        pytest.skip(
            f"Reference data not found: {dataset_dir}\n"
            "Run generate_r_reference.R first:\n"
            "  pixi run -e r-genebasis Rscript "
            "software/geneBasis/pyGeneBasis/tests/generate_r_reference.R"
        )
    counts = scipy.io.mmread(dataset_dir / "counts.mtx")
    # MTX from R is always written genes×cells; transpose to cells×genes for AnnData
    counts = scipy.sparse.csr_matrix(counts.T)
    obs = pd.read_csv(dataset_dir / "obs.csv", index_col=0)
    var = pd.read_csv(dataset_dir / "var.csv", index_col=0)
    adata = ad.AnnData(X=counts, obs=obs, var=var)
    return adata


def _load_r_outputs(dataset_dir: Path) -> dict[str, pd.DataFrame]:
    """Load all R reference CSVs as a name → DataFrame dict."""
    rout = dataset_dir / "r_outputs"
    if not rout.exists():
        pytest.skip(
            f"R outputs not found: {rout}\n"
            "Run generate_r_reference.R first."
        )
    def _load_one(f):
        # R writes row names as an unnamed first column ("","V1","V2",...).
        # Detect this and set index_col=0 only for those files so that .values
        # gives the numeric data without the row-name string column.
        with open(f) as fh:
            first_col = fh.readline().split(",")[0].strip('"')
        return pd.read_csv(f, index_col=0 if first_col == "" else None)

    return {f.stem: _load_one(f) for f in sorted(rout.glob("*.csv"))}


def overlap_fraction(a: list | np.ndarray, b: list | np.ndarray) -> float:
    """Fraction of elements in a that appear in b."""
    return len(set(a) & set(b)) / len(set(a))


def knn_overlap(idx_a: np.ndarray, idx_b: np.ndarray) -> float:
    """Mean per-row fraction of neighbours in common between two index matrices."""
    fracs = [
        len(set(row_a) & set(row_b)) / len(row_a)
        for row_a, row_b in zip(idx_a, idx_b)
    ]
    return float(np.mean(fracs))


def spearman_r(a: np.ndarray, b: np.ndarray) -> float:
    """Spearman rank correlation between two 1-D arrays."""
    from scipy.stats import spearmanr
    return float(spearmanr(a, b).statistic)


